#!/usr/bin/env python3
import os
from jinja2 import Environment, FileSystemLoader

def main():
    # Absolute path to the directory containing generate.py
    script_dir = os.path.dirname(os.path.abspath(__file__))
    # Since your template is right here, point the loader at script_dir
    env = Environment(
        loader=FileSystemLoader(script_dir),
        trim_blocks=True,
        lstrip_blocks=True
    )

    # Now Jinja2 will find hello.cpp.jinja2 in the same folder
    tmpl = env.get_template('loader.cpp.jinja2')

    rendered = tmpl.render(message='Hello, world!')

    out_dir = os.path.join(script_dir, '..', 'src', 'generated')
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, 'AutoGenerated.cpp')
    with open(out_path, 'w') as f:
        f.write(rendered)

    print(f'✓ Generated: {out_path}')

if __name__ == '__main__':
    main()